namespace SweetBridge.Web.Services.Content;

/// <summary>
/// Блок текста информационной страницы.
/// </summary>
/// <param name="Title">Заголовок блока.</param>
/// <param name="Body">Текст блока.</param>
public sealed record ContentBlock(string Title, string Body);

/// <summary>
/// Информационная страница с заголовком, лидом и блоками.
/// </summary>
/// <param name="Slug">Адрес страницы.</param>
/// <param name="Title">Заголовок.</param>
/// <param name="Lead">Вводный абзац.</param>
/// <param name="Blocks">Блоки текста.</param>
public sealed record ContentPage(string Slug, string Title, string Lead, IReadOnlyList<ContentBlock> Blocks);

/// <summary>
/// Доступ к информационным страницам: доставка, оплата, документы.
/// </summary>
public interface IContentService
{
    /// <summary>
    /// Возвращает список всех статей.
    /// </summary>
    /// <returns>Статьи информационного раздела.</returns>
    IReadOnlyList<ContentPage> GetAll();

    /// <summary>
    /// Возвращает статью по адресу.
    /// </summary>
    /// <param name="slug">Адрес статьи.</param>
    /// <returns>Статья или <see langword="null"/>, если адрес неизвестен.</returns>
    ContentPage? Find(string? slug);
}

